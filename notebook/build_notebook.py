md(r"""
## 6. How the stored outputs were produced (optional, long-running)

These cells document the full pipeline. Set `RUN_PIPELINE = True` only on a machine with BIRD downloaded,
Cube running on :4000 (`cd cube && npm install && npm run dev`), Ollama, and a 16 GB GPU for training.
Runtimes on an RTX 5070 Ti: one 332-question eval ≈ 10–25 min; 7B LoRA ≈ 5.3 h, 14B ≈ 9 h.
""")
code(r"""
RUN_PIPELINE = False
STEPS = [
    # data
    "python scripts/download_bird.py",
    "python scripts/build_duckdb.py --bird-dir data/bird --out data/bird.duckdb --db formula_1 --db student_club --db superhero --db toxicology --db california_schools",
    "python scripts/gen_cube_models.py --bird-dir data/bird --out cube/model --db formula_1 --db student_club --db superhero --db toxicology --db california_schools",
    "python scripts/build_training_data.py --bird-dir data/bird_train --out data/training   # needs train.zip; already in training_data/",
    "python scripts/make_sft.py --data training_data --out data/sft",
    # baseline arms
    "python -m harness.evaluate --db formula_1 --db student_club --ids-file splits/test_ids.json --no-evidence --model ollama_chat/qwen2.5-coder:7b --setup harness-v4.2-7b-nohint --out runs/test_nohint_harness_7b.jsonl",
    "python -m harness.evaluate --db formula_1 --db student_club --ids-file splits/test_ids.json --no-evidence --model ollama_chat/qwen2.5-coder:14b --setup harness-v4.2-14b-nohint --out runs/test_nohint_harness_14b.jsonl",
    # LoRA arm (7B; same with 14B and --max-len 4096)
    "python scripts/train_lora.py --base Qwen/Qwen2.5-Coder-7B-Instruct --out lora/qwen7b",
    "python scripts/export_ollama.py --base Qwen/Qwen2.5-Coder-7B-Instruct --adapter lora/qwen7b/final --llama-cpp ../llama.cpp --quantize ../llama.cpp/build/bin/llama-quantize --ollama-base qwen2.5-coder:7b --name qwen7b-cube-lora",
    "python -m harness.evaluate --db formula_1 --db student_club --ids-file splits/test_ids.json --no-evidence --model ollama_chat/qwen7b-cube-lora --setup lora-v4.2-7b-nohint --out runs/test_nohint_lora_7b.jsonl",
    # prompt-offloading arms
    "python scripts/make_sft.py --data training_data --profile lean --out data/sft_lean",
    "python scripts/synth_schema_qa.py --db formula_1 --n 800 --db student_club --n 500 --out data/synth/synth.jsonl --audit",
    "python scripts/make_sft.py --data training_data --profile noschema --synthetic data/synth/synth.jsonl --out data/sft_noschema",
    "python -m harness.evaluate --db formula_1 --db student_club --ids-file splits/test_ids.json --no-evidence --profile lean --model ollama_chat/qwen7b-cube-lean --setup lora-lean-7b-nohint --out runs/test_nohint_lean_7b.jsonl",
]
for s in STEPS:
    print("$", s)
    if RUN_PIPELINE:
        subprocess.run(s.split("#")[0], shell=True, cwd=ROOT, check=True)
""")
